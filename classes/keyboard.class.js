/**
 * Represents the current state of user input keys.
 */
class Keyboard {
/**
 * Indicates if the left key is pressed.
 * @type {boolean}
 */
LEFT = false;

/**
 * Indicates if the right key is pressed.
 * @type {boolean}
 */
RIGHT = false;

/**
 * Indicates if the up key (jump) is pressed.
 * @type {boolean}
 */
UP = false;

/**
 * Indicates if the space key (throw/action) is pressed.
 * @type {boolean}
 */
SPACE = false;
}